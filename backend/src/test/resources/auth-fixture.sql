CREATE TABLE region_neighbors (region_id BIGINT NOT NULL, neighbor_region_id BIGINT NOT NULL, PRIMARY KEY (region_id, neighbor_region_id));
CREATE TABLE posts (id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NOT NULL, region_id BIGINT NOT NULL, category VARCHAR(10) NOT NULL,
    title VARCHAR(100) NOT NULL, body TEXT NOT NULL, like_count INT DEFAULT 0 NOT NULL, comment_count INT DEFAULT 0 NOT NULL,
    is_home_tip BOOLEAN DEFAULT FALSE NOT NULL, status VARCHAR(10) DEFAULT 'VISIBLE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, deleted_at TIMESTAMP,
    deleted_by BIGINT, delete_reason VARCHAR(200),
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE);
CREATE TABLE post_likes (post_id BIGINT NOT NULL, user_id BIGINT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (post_id, user_id), FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE);
CREATE TABLE comments (id BIGINT AUTO_INCREMENT PRIMARY KEY, post_id BIGINT NOT NULL, user_id BIGINT NOT NULL, parent_id BIGINT,
    body VARCHAR(200) NOT NULL, status VARCHAR(10) DEFAULT 'VISIBLE' NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, deleted_at TIMESTAMP, deleted_by BIGINT, delete_reason VARCHAR(200),
    FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE);
CREATE TABLE reports (id BIGINT AUTO_INCREMENT PRIMARY KEY, reporter_id BIGINT NOT NULL, target_type VARCHAR(10) NOT NULL, target_id BIGINT NOT NULL,
    reason VARCHAR(20) NOT NULL, detail VARCHAR(200), status VARCHAR(10) DEFAULT 'RECEIVED' NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    handled_by BIGINT, handled_at TIMESTAMP, target_author_snapshot VARCHAR(12), target_text_snapshot VARCHAR(200),
    UNIQUE (reporter_id, target_type, target_id));
CREATE TABLE post_attachments (post_id BIGINT NOT NULL, file_id BIGINT NOT NULL, sort_order TINYINT DEFAULT 0 NOT NULL,
    PRIMARY KEY (post_id, file_id), UNIQUE (file_id), UNIQUE (post_id, sort_order),
    FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE, FOREIGN KEY (file_id) REFERENCES uploaded_files (id) ON DELETE CASCADE);
